#!/usr/bin/env node
/**
 * Regenerates `src/data/art.ts` from `art/manifest.json` plus the measured
 * `sprite-metadata.json` next to every exported sheet under
 * `public/assets/generated/`.
 *
 * Nothing about frame geometry, animation timing or per-action scale is
 * hand-baked in the registry: geometry and QC numbers come from
 * `sprite-metadata.json` (measured by sprite-forge at export time), and every
 * curated fact a human must supply (facing, which action anchors the scale
 * profile, icon frame names, texture/animation aliases) lives in
 * `art/manifest.json`. Re-running this script after a re-export or a manifest
 * edit is the only way `src/data/art.ts` should ever change.
 *
 * Usage (run from the `template/` directory):
 *   node scripts/gen-art-registry.mjs           # regenerate src/data/art.ts
 *   node scripts/gen-art-registry.mjs --check   # verify it is up to date; exit 1 on drift
 *
 * ---------------------------------------------------------------------------
 * art/manifest.json asset schema (fields this script reads):
 *
 *   id           string   Directory name under outputRoot/<group>/<id>/.
 *                          Also the default Phaser texture/animation key.
 *   key          string?  Overrides the emitted texture key when it differs
 *                          from `id` (e.g. props are namespaced 'prop-<id>').
 *   rows, cols   number   Export grid. Cross-checked against the asset's own
 *                          sprite-metadata.json `grid`; mismatch is a hard error.
 *   facesRight   bool?    Default true. Set false to record that the unflipped
 *                          art faces left (mirrors through `artFacesRight`).
 *   baseAction   bool?    True on exactly one asset per multi-action group.
 *                          Its `outputSubjectHeightMean` becomes that group's
 *                          reference height; every sibling in the group gets
 *                          `scale = baseHeight / thisHeight`, so switching
 *                          actions never visibly resizes the character.
 *   loop         bool?    Default true. Whether the generated Phaser animation
 *                          repeats.
 *   duration     number?  Overrides sprite-metadata.json's `output.durationMs`
 *                          as ms-per-frame. Set to 0 on a multi-frame sheet
 *                          that must NOT get an animation (icon sheets
 *                          addressed by frame index instead).
 *   textureAlias string?  Adds `TEXTURE.<alias> = '<key>'` for an asset
 *                          gameplay code addresses by a stable name.
 *   animAlias    string?  Adds `ANIM.<alias> = '<key>'` for an asset gameplay
 *                          code plays by a named animation constant.
 *   icons        string[]?On an icon sheet: index = frame number, each name
 *                          adds `ICON.<name> = { key: '<key>', frame: <i> }`.
 *
 * Every emitted row carries its manifest `group`. `src/scenes/preload.ts` loads
 * a row only when its group is in the active slice's `ART_GROUPS`, and
 * `scripts/new-game.sh` deletes the `public/assets/generated/<group>/`
 * directories the chosen family does not list before re-running this script. A
 * group whose directory is gone is therefore "pruned on purpose": no rows, but
 * its aliases stay (flagged) so another family's modules still compile. A
 * missing asset INSIDE a present group remains a hard error.
 *
 * A group's `note` (if present) becomes the doc-comment above that group's
 * block in the generated file, so `art/manifest.json` stays the single place
 * that explains what an asset is for.
 *
 * The registry must also still COMPILE against its readers: before anything is
 * written, every `TEXTURE`/`ANIM`/`ICON` alias that `src/` reads must exist in
 * the registry this run would emit. An art run that drops an asset the code
 * still addresses fails HERE, by name, instead of emitting a registry that
 * produces TS2339 errors later (see `assertConsumersResolve`).
 * ---------------------------------------------------------------------------
 */

import { readdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs';
import { relative, resolve } from 'node:path';

const ROOT = process.cwd();
const MANIFEST_PATH = resolve(ROOT, 'art/manifest.json');
const SRC_DIR = resolve(ROOT, 'src');
const OUTPUT_PATH = resolve(ROOT, 'src/data/art.ts');
const CHECK = process.argv.includes('--check');

const HEADER =
  '// GENERATED by scripts/gen-art-registry.mjs — do not edit by hand; edit art/manifest.json + regenerate.\n';

/** Reads a PNG's pixel dimensions from its IHDR chunk (bytes 16-23), no deps. */
function pngDimensions(path) {
  const fd = readFileSync(path);
  if (fd.length < 24 || fd.readUInt32BE(0) !== 0x89504e47) {
    throw new Error(`${path}: not a PNG file`);
  }
  return { width: fd.readUInt32BE(16), height: fd.readUInt32BE(20) };
}

function readJson(path) {
  return JSON.parse(readFileSync(path, 'utf8'));
}

function assetDir(group, id) {
  return resolve(ROOT, 'public/assets/generated', group, id);
}

function loadMetadata(group, id) {
  const path = resolve(assetDir(group, id), 'sprite-metadata.json');
  if (!existsSync(path)) {
    throw new Error(`Missing sprite-metadata.json for ${group}/${id} at ${path}`);
  }
  return readJson(path);
}

/** Emits `key: value` pairs for one SpriteAsset object literal, in a fixed field order. */
function formatAsset(fields) {
  const parts = [];
  for (const [k, v] of fields) {
    if (v === undefined) continue;
    parts.push(`${k}: ${typeof v === 'string' ? `'${v}'` : v}`);
  }
  return `  { ${parts.join(', ')} },`;
}

function round3(n) {
  return Math.round(n * 1000) / 1000;
}

/** Every `.ts` file under `src/`, minus the generated registry itself. */
function sourceFiles(dir = SRC_DIR, out = []) {
  if (!existsSync(dir)) return out;
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const full = resolve(dir, entry.name);
    if (entry.isDirectory()) sourceFiles(full, out);
    else if (entry.isFile() && entry.name.endsWith('.ts') && full !== OUTPUT_PATH) out.push(full);
  }
  return out;
}

/**
 * `KIND.alias` -> the files that read it, for every `TEXTURE`/`ANIM`/`ICON`
 * member access in the game's own code (dot or quoted-bracket form).
 */
function aliasReads() {
  const reads = new Map();
  for (const file of sourceFiles()) {
    const text = readFileSync(file, 'utf8');
    for (const m of text.matchAll(/\b(TEXTURE|ANIM|ICON)(?:\.([A-Za-z_$][\w$]*)|\[\s*'([^']+)'\s*\])/g)) {
      const id = `${m[1]}.${m[2] ?? m[3]}`;
      const at = reads.get(id);
      if (at) at.add(file);
      else reads.set(id, new Set([file]));
    }
  }
  return reads;
}

/** The alias names the CURRENT src/data/art.ts declares, per map. */
function declaredInExistingRegistry() {
  const out = new Set();
  if (!existsSync(OUTPUT_PATH)) return out;
  const text = readFileSync(OUTPUT_PATH, 'utf8');
  for (const kind of ['TEXTURE', 'ICON', 'ANIM']) {
    const m = new RegExp(`export const ${kind} = \\{([\\s\\S]*?)\\n\\} as const;`).exec(text);
    if (!m) continue;
    for (const row of m[1].matchAll(/^\s*'?([\w$-]+)'?:/gm)) out.add(`${kind}.${row[1]}`);
  }
  return out;
}

/**
 * A regenerated registry must still COMPILE against the code that reads it.
 * Measured failure: an art run rewrote `art/manifest.json` without the
 * template's `coin`, `xpOrb`, `bullet`, `hitSpark`, `heart` and `backdrop`
 * aliases, this script happily emitted a registry without them, and the 8
 * resulting TS2339 errors surfaced only after twelve art agents had finished.
 * The generator knew every removed alias and said nothing.
 *
 * So: every `TEXTURE`/`ANIM`/`ICON` member the code reads must exist in the
 * registry about to be written. Referenced-but-removed is a hard error naming
 * the aliases, their readers, and whether the previous registry had them.
 * Referenced-but-PRUNED (the group's directory is gone, the alias survives as
 * a compile stub) is a warning: cross-family dead code legitimately reads
 * those, and `ArtSlot` consumers guard with `scene.textures.exists`.
 */
function assertConsumersResolve(textureAliases, animAliases, iconEntries) {
  const declared = new Set();
  const pruned = new Set();
  for (const [kind, rows, groupAt] of [
    ['TEXTURE', textureAliases, 2],
    ['ANIM', animAliases, 2],
    ['ICON', iconEntries, 3],
  ]) {
    for (const row of rows) {
      const id = `${kind}.${row[0]}`;
      declared.add(id);
      // A pruned row carries the group name in a trailing slot (see
      // `notShipped`): [alias, key, group] for TEXTURE/ANIM, [name, key,
      // frame, group] for ICON. Indexed, not "last element" — an icon's
      // `frame` is a number and frame 3 is not a group name.
      if (row[groupAt]) pruned.add(id);
    }
  }

  const reads = aliasReads();
  const previously = declaredInExistingRegistry();
  const missing = [...reads].filter(([id]) => !declared.has(id));
  if (missing.length > 0) {
    const lines = missing.map(([id, files]) => {
      const where = [...files].map((f) => relative(ROOT, f)).sort().join(', ');
      const note = previously.has(id) ? ' — declared by the CURRENT registry, so this run REMOVES it' : '';
      return `  ${id}  read by ${where}${note}`;
    });
    throw new Error(
      `art/manifest.json no longer declares ${missing.length} art alias(es) that src/ still reads.\n` +
        `${lines.join('\n')}\n\n` +
        'Writing this registry would produce exactly that many TS2339 errors. Either restore the\n' +
        'asset rows (with their `textureAlias` / `animAlias` / `icons` names) in art/manifest.json,\n' +
        'or update the reader(s) above to the aliases this game actually ships.',
    );
  }

  const stubs = [...reads].filter(([id]) => pruned.has(id));
  for (const [id, files] of stubs) {
    const where = [...files].map((f) => relative(ROOT, f)).sort().join(', ');
    console.warn(`warn: ${id} belongs to a pruned art group — nothing loads it; ${where} renders the fallback.`);
  }
}

function main() {
  const manifest = readJson(MANIFEST_PATH);

  // A group whose directory under `public/assets/generated/` is gone was
  // pruned on purpose: `scripts/new-game.sh` deletes every group the chosen
  // family does not use, so a game only ships the art its slice loads. Those
  // groups emit no registry rows (nothing to load) but keep their alias
  // constants, so shared modules that belong to another family still compile.
  // A MISSING ASSET INSIDE AN EXPORTED GROUP stays a hard error — that is a
  // broken export, not a prune.
  const pruned = new Set(
    manifest.groups
      .map((g) => g.group)
      .filter((g) => !existsSync(resolve(ROOT, 'public/assets/generated', g))),
  );

  /** @type {Map<string, number>} group name -> base outputSubjectHeightMean */
  const baseHeights = new Map();
  for (const group of manifest.groups) {
    if (pruned.has(group.group)) continue;
    const base = group.assets.find((a) => a.baseAction);
    if (!base) continue;
    const meta = loadMetadata(group.group, base.id);
    baseHeights.set(group.group, meta.qc.summary.outputSubjectHeightMean);
  }

  const spriteBlocks = [];
  const imageBlocks = [];
  const textureAliases = [];
  const animAliases = [];
  const iconEntries = [];

  for (const group of manifest.groups) {
    const spriteLines = [];
    const imageLines = [];
    const groupPruned = pruned.has(group.group);

    for (const asset of group.assets) {
      if (groupPruned) {
        const key = asset.key ?? asset.id;
        if (asset.textureAlias) textureAliases.push([asset.textureAlias, key, group.group]);
        if (asset.animAlias) animAliases.push([asset.animAlias, key, group.group]);
        if (asset.icons) {
          asset.icons.forEach((name, frame) => iconEntries.push([name, key, frame, group.group]));
        }
        continue;
      }

      const meta = loadMetadata(group.group, asset.id);
      if (meta.grid.rows !== asset.rows || meta.grid.cols !== asset.cols) {
        throw new Error(
          `${group.group}/${asset.id}: manifest grid ${asset.rows}x${asset.cols} does not match ` +
            `sprite-metadata.json grid ${meta.grid.rows}x${meta.grid.cols}`,
        );
      }

      const key = asset.key ?? asset.id;
      const frames = asset.rows * asset.cols;
      const duration = asset.duration ?? (frames > 1 ? meta.output.durationMs : 0);
      const loop = asset.loop ?? (frames > 1 && duration > 0);

      let path;
      let frameWidth;
      let frameHeight;
      if (frames > 1) {
        path = `assets/generated/${group.group}/${asset.id}/sprite-sheet.png`;
        const dims = pngDimensions(resolve(assetDir(group.group, asset.id), 'sprite-sheet.png'));
        if (dims.width % asset.cols !== 0 || dims.height % asset.rows !== 0) {
          throw new Error(
            `${group.group}/${asset.id}: sheet ${dims.width}x${dims.height} does not divide evenly ` +
              `into a ${asset.rows}x${asset.cols} grid`,
          );
        }
        frameWidth = dims.width / asset.cols;
        frameHeight = dims.height / asset.rows;
      } else {
        path = `assets/generated/${group.group}/${asset.id}/sprite.png`;
        const dims = pngDimensions(resolve(assetDir(group.group, asset.id), 'sprite.png'));
        frameWidth = dims.width;
        frameHeight = dims.height;
      }

      let scale;
      const baseHeight = baseHeights.get(group.group);
      if (baseHeight !== undefined && !asset.baseAction && frames > 1) {
        scale = round3(baseHeight / meta.qc.summary.outputSubjectHeightMean);
      }

      const fields = [
        ['key', key],
        ['group', group.group],
        ['path', path],
        ['frameWidth', frameWidth],
        ['frameHeight', frameHeight],
        ['frames', frames],
        ['duration', duration],
        ['loop', loop],
      ];
      if (scale !== undefined) fields.push(['scale', scale]);
      if (asset.facesRight === false) fields.push(['facesRight', false]);

      const line = formatAsset(fields);
      if (frames > 1) spriteLines.push(line);
      else imageLines.push(line);

      if (asset.textureAlias) textureAliases.push([asset.textureAlias, key]);
      if (asset.animAlias) animAliases.push([asset.animAlias, key]);
      if (asset.icons) {
        asset.icons.forEach((name, frame) => iconEntries.push([name, key, frame]));
      }
    }

    const heading =
      group.note ??
      group.group
        .split('-')
        .map((w) => w[0].toUpperCase() + w.slice(1))
        .join(' ');
    if (spriteLines.length > 0) {
      const allStatic = group.assets
        .filter((a) => a.rows * a.cols > 1)
        .every((a) => (a.duration ?? loadMetadata(group.group, a.id).output.durationMs) <= 0);
      const suffix = allStatic
        ? ' Loaded as spritesheets so a frame index can be selected; no animation is created.'
        : '';
      spriteBlocks.push(`  // ${heading}${suffix}\n${spriteLines.join('\n')}`);
    }
    if (imageLines.length > 0) {
      imageBlocks.push(`  // ${heading}\n${imageLines.join('\n')}`);
    }
  }

  // Before anything is written: the registry this run would emit must still
  // satisfy the code that reads it (see `assertConsumersResolve`).
  assertConsumersResolve(textureAliases, animAliases, iconEntries);

  // A pruned group's aliases stay in the constant maps (dead code from another
  // family still has to compile) but are flagged: nothing loads them, so using
  // one would render a missing texture.
  const notShipped = (group) => (group ? ` // not shipped: group '${group}' pruned` : '');
  /** Quote a map key unless it is a valid identifier (aliases like `bg-layer-0`). */
  const asKey = (name) => (/^[A-Za-z_$][A-Za-z0-9_$]*$/.test(name) ? name : `'${name}'`);
  const textureEntries = textureAliases
    .map(([alias, key, group]) => `  ${asKey(alias)}: '${key}',${notShipped(group)}`)
    .join('\n');
  const animEntries = animAliases
    .map(([alias, key, group]) => `  ${asKey(alias)}: '${key}',${notShipped(group)}`)
    .join('\n');
  const iconLines = iconEntries
    .map(
      ([name, key, frame, group]) =>
        `  ${asKey(name)}: { key: '${key}', frame: ${frame} },${notShipped(group)}`,
    )
    .join('\n');

  const output = `${HEADER}/**
 * Generated-art registry: the only place that knows asset paths and frame
 * geometry. Every sheet under \`public/assets/generated/\` was produced by the
 * \`game-art\` skill (native generate_image + sprite-forge export) against
 * \`art/style.json\`, so the whole set shares one style contract.
 *
 * Frame geometry and per-action scale come from each asset's
 * \`sprite-metadata.json\` and \`art/manifest.json\` — never hand-guessed. To
 * change a row here, edit the manifest (or re-export the asset) and re-run
 * \`node scripts/gen-art-registry.mjs\`.
 *
 * Pure data, no Phaser import.
 */

/**
 * How a slice's tuning points a gameplay role at loaded art: \`{ key }\` for a
 * single-image texture, \`{ key, frame }\` for one cell of a sheet (the shape
 * \`ICON\` entries already have). One declaration for every slice — a slot is
 * addressing art, which is what this registry is for.
 *
 * Resolve it once, at construction: when
 * \`scene.textures.exists(slot.key)\` is false the slice draws its procedural
 * fallback instead, so a pruned art group degrades instead of rendering
 * missing-texture boxes. Tint belongs to that fallback only — generated art
 * carries its own colour.
 */
export interface ArtSlot {
  /** Texture key from \`TEXTURE\`/\`ANIM\`/\`ICON\` (or a raw registry \`key\`). */
  key: string;
  /** Frame on a multi-frame sheet: index, or an atlas frame name. */
  frame?: string | number;
}

export interface SpriteAsset {
  /** Phaser texture key; also the animation key when \`frames > 1\`. */
  key: string;
  /**
   * \`art/manifest.json\` group this asset belongs to. \`PreloadScene\` loads a
   * row only when its group is listed in the active slice's \`ART_GROUPS\`, so a
   * game downloads the art its gameplay actually uses and nothing else.
   */
  group: string;
  /** Path under \`public/\`. */
  path: string;
  frameWidth: number;
  frameHeight: number;
  frames: number;
  /** ms per frame; ignored when \`frames === 1\`. */
  duration: number;
  loop: boolean;
  /**
   * Display-size compensation. Generated actions do not fill their cell to the
   * same height, so switching animation would visibly resize the character.
   * The entity multiplies its tuned size by this factor, which is
   * \`baseActionHeight / thisActionHeight\` (see \`baseAction\` in
   * art/manifest.json). Default 1.
   */
  scale?: number;
  /**
   * Which way the unflipped art faces. Some art reads as moving LEFT (cloak
   * trails right), so flipping on \`velocity.x < 0\` would face it backwards.
   * Default true.
   */
  facesRight?: boolean;
}

/** Animated sheets: loaded as spritesheets, one animation created per entry. */
export const SPRITES: readonly SpriteAsset[] = [
${spriteBlocks.join('\n\n')}
] as const;

/** Single-image textures: no animation, no frame slicing. */
export const IMAGES: readonly SpriteAsset[] = [
${imageBlocks.join('\n\n')}
] as const;

const BY_KEY: Record<string, SpriteAsset> = {};
for (const asset of SPRITES) BY_KEY[asset.key] = asset;

/** Display-size factor for an animation key (1 when the asset needs none). */
export function artScale(key: string): number {
  return BY_KEY[key]?.scale ?? 1;
}

/** True when the unflipped art faces right. */
export function artFacesRight(key: string): boolean {
  return BY_KEY[key]?.facesRight ?? true;
}

/** Static texture keys, so gameplay code never types a string literal. */
export const TEXTURE = {
${textureEntries}
} as const;

/** Frame index per icon inside the icon sheets. */
export const ICON = {
${iconLines}
} as const;

/**
 * UI chrome (panels, buttons, bar housings) is NOT art: it is drawn with
 * primitives in \`ui/primitives.ts\` so it adapts to any size and re-skins with
 * \`PALETTE\`. Generated art is used for content that is genuinely drawing —
 * icons, the title emblem, the backdrop and every entity.
 */

/** Animation keys, so gameplay code never types a string literal. */
export const ANIM = {
${animEntries}
} as const;
`;

  if (CHECK) {
    const existing = existsSync(OUTPUT_PATH) ? readFileSync(OUTPUT_PATH, 'utf8') : '';
    if (existing !== output) {
      console.error(
        'src/data/art.ts is stale: it does not match art/manifest.json + sprite-metadata.json.\n' +
          'Run `node scripts/gen-art-registry.mjs` to regenerate it, then commit the result.',
      );
      process.exit(1);
    }
    console.log('src/data/art.ts is up to date.');
    return;
  }

  writeFileSync(OUTPUT_PATH, output);
  console.log(`Wrote ${OUTPUT_PATH}`);
}

main();

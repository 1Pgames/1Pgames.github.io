/**
 * Stage 3 of `verify.sh`: PRODUCER -> CONSUMER edges.
 *
 * Frozen interface contracts froze *types*, not *edges*. Every blocker of the
 * last build's review gate was one shape: a workstream built its half correctly
 * against the contract, and the other half was never connected. An unimported
 * module typechecks perfectly forever. A fully-built `ui/coachBeats.ts` shipped
 * with ZERO importers. `bag.pinCasket()` shipped with no UI call site — and its
 * selftest was the ONLY caller, so the selftest MASKED the deadness. Content
 * rotted the same way: 12 dead-content classes, including a tuning number
 * behind a structurally unreachable gate and perk rows read by nobody.
 *
 * So this stage asks the one question no type system asks: *who reads this?*
 *
 *   E1  every module under `src/` is reachable from the game entry
 *   E2  every exported value has a non-selftest importer outside its own dir
 *   E2b every public method of an exported class has a caller that is not a selftest
 *   E3  every tuning leaf has >= 1 reader in `src/`
 *   E4  every content value that indexes a registry is a key of that registry
 *
 * A selftest never counts as a consumer. That is the masking rule, and it is
 * the entire reason `pinCasket` reached the review gate looking alive.
 *
 * PROVENANCE — why `kit-manifest.json` exists. The template ships a ten-family
 * genre kit; an arena game legitimately never imports `core/board/*`. Failing
 * those would make the gate unshippable, and a gate agents switch off is worse
 * than no gate. The manifest is the template's own export inventory, GENERATED
 * (`--write-manifest`), never hand-written — it is the mechanical answer to
 * "did THIS build author this symbol?". Kit surface unused by the chosen family
 * is a note; anything this build wrote and left unwired is a failure.
 *
 * Run: node --import ./scripts/ts-resolve.mjs scripts/consumer-edge-check.mjs
 *      [--root <game-dir>] [--json] [--write-manifest]
 */
import {
  ROOT, listSourceFiles, parseModule, resolveSpec, isSelftest, sourceOf,
  loadDataModules, tuningRoots, tuningLeaves, scanTuningReads, leafIsRead, report,
} from './contract-lib.mjs';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const failures = [];
const notes = [];

const files = listSourceFiles();
const modules = new Map(files.map((rel) => [rel, parseModule(rel)]));

/* ------------------------------------------------------------ provenance -- */

/**
 * The kit inventory sits next to the SCRIPT, not under `--root`: it describes
 * the template a tree was scaffolded from. A game's own copy is the same file,
 * carried over by the scaffold.
 */
const MANIFEST = join(dirname(fileURLToPath(import.meta.url)), 'kit-manifest.json');

if (process.argv.includes('--write-manifest')) {
  const { loaded: kitData } = await loadDataModules();
  const tuning = {};
  for (const root of tuningRoots(kitData)) tuning[root.name] = tuningLeaves(root.value).sort();
  const inventory = {
    note: 'GENERATED by `node scripts/consumer-edge-check.mjs --write-manifest` in template/. Never hand-edit: it is the provenance oracle for the consumer-edge gate — it answers "did THIS build author this?" and nothing else.',
    modules: Object.fromEntries(
      [...modules].map(([rel, mod]) => [rel, [...new Set(mod.exports.map((s) => s.name))].sort()]),
    ),
    tuning,
  };
  writeFileSync(MANIFEST, `${JSON.stringify(inventory, null, 2)}\n`);
  console.log(
    `wrote ${MANIFEST}: ${Object.keys(inventory.modules).length} kit modules, `
    + `${Object.values(tuning).reduce((n, l) => n + l.length, 0)} kit tuning leaves`,
  );
  process.exit(0);
}

const manifest = existsSync(MANIFEST) ? JSON.parse(readFileSync(MANIFEST, 'utf8')) : { modules: {}, tuning: {} };
const kit = manifest.modules ?? {};
const kitTuning = manifest.tuning ?? {};
if (!existsSync(MANIFEST)) {
  notes.push('no scripts/kit-manifest.json: every module, symbol and tuning leaf is treated as build-authored');
}
/** True when the template shipped this exact path/symbol — i.e. this build did not author it. */
const isKitModule = (rel) => Object.hasOwn(kit, rel);
const isKitSymbol = (rel, name) => isKitModule(rel) && kit[rel].includes(name);
const isKitTuning = (root, leaf) => (kitTuning[root] ?? []).includes(leaf);

// Running inside the template itself, the manifest and the tree describe the
// same thing, so any divergence is staleness. Say so loudly: a stale manifest
// silently reclassifies new kit surface as build-authored in every game
// scaffolded afterwards, which is a gate lying about provenance.
const IN_TEMPLATE = ROOT === dirname(dirname(fileURLToPath(import.meta.url)));
if (IN_TEMPLATE && existsSync(MANIFEST)) {
  const added = files.filter((rel) => !Object.hasOwn(kit, rel));
  const removed = Object.keys(kit).filter((rel) => !files.includes(rel));
  if (added.length > 0 || removed.length > 0) {
    notes.push(
      `kit-manifest.json is STALE (+${added.length} / -${removed.length} modules: `
      + `${[...added.map((r) => `+${r}`), ...removed.map((r) => `-${r}`)].slice(0, 8).join(', ')}) — `
      + 'regenerate with `node --import ./scripts/ts-resolve.mjs scripts/consumer-edge-check.mjs --write-manifest`',
    );
  }
}

/* --------------------------------------------- the import graph, resolved -- */

/** rel -> Set<rel> of the modules it imports (relative specifiers only). */
const edges = new Map();
/** rel -> Array<{ from, names, namespace, typeOnly }> — who imports me, and what. */
const importedBy = new Map(files.map((rel) => [rel, []]));

for (const [rel, mod] of modules) {
  const targets = new Set();
  for (const entry of mod.imports) {
    const target = resolveSpec(rel, entry.spec);
    if (target === null) continue;
    targets.add(target);
    const list = importedBy.get(target);
    if (list !== undefined) {
      list.push({ from: rel, names: entry.named, namespace: entry.namespace, typeOnly: entry.typeOnly });
    }
  }
  edges.set(rel, targets);
}

/* ------------------------------------- E1: reachability from the entry point */

function reach(roots) {
  const seen = new Set();
  const queue = roots.filter((rel) => modules.has(rel));
  while (queue.length > 0) {
    const rel = queue.pop();
    if (seen.has(rel)) continue;
    seen.add(rel);
    for (const next of edges.get(rel) ?? []) if (!seen.has(next)) queue.push(next);
  }
  return seen;
}

const GAME_ENTRY = 'src/main.ts';
const harnessRoots = files.filter((rel) => isSelftest(rel) || rel === 'src/sim/cli.ts');
const liveModules = reach([GAME_ENTRY]);
const harnessModules = reach(harnessRoots);

if (!modules.has(GAME_ENTRY)) failures.push(`no game entry at ${GAME_ENTRY}: nothing can be proven reachable`);

let unusedKitModules = 0;
for (const rel of files) {
  if (liveModules.has(rel)) continue;
  if (isSelftest(rel) || rel === 'src/sim/cli.ts') continue;
  if (rel.startsWith('src/sim/') && harnessModules.has(rel)) continue; // sim harness by design
  const why = harnessModules.has(rel)
    ? 'only a selftest/sim harness reaches it — a harness is not a consumer'
    : 'nothing imports it';
  if (isKitModule(rel)) {
    unusedKitModules += 1;
    continue;
  }
  failures.push(`orphan module ${rel}: unreachable from ${GAME_ENTRY} (${why})`);
}
if (unusedKitModules > 0) {
  notes.push(`${unusedKitModules} template kit module(s) unused by this family — pruning candidates, not defects`);
}

/* ----------------------------------- E2: per-symbol consumers outside the dir */

/**
 * Held to a hard rule: exported VALUES (const/function/class/enum). A value with
 * no importer is code that runs nowhere.
 *
 * Exported TYPES are noted, not failed: an `interface FooOptions` is routinely
 * satisfied by an inline object literal at the call site and never imported by
 * name, so failing types would fail correct code. The note still matters —
 * `StatKey` was implemented twice against disjoint key sets precisely because
 * nobody looked at who imported which declaration.
 */
const TYPE_KINDS = new Set(['type', 'interface']);
const sameDirOnly = [];

for (const [rel, mod] of modules) {
  if (isSelftest(rel)) continue;
  if (rel === GAME_ENTRY) continue; // the entry is loaded by index.html, not imported
  const ownDir = dirname(rel);
  const consumers = importedBy.get(rel) ?? [];
  const namespaceConsumers = consumers.filter((c) => c.namespace && !isSelftest(c.from));

  for (const sym of mod.exports) {
    const byName = consumers.filter((c) => c.names.includes(sym.name));
    const real = byName.filter((c) => !isSelftest(c.from));
    if (namespaceConsumers.length > 0) continue; // `import * as m` consumes the whole surface

    if (real.length === 0) {
      const detail = byName.length > 0
        ? `imported ONLY by ${byName.map((c) => c.from).join(', ')} — a selftest is not a consumer`
        : 'no module imports it';
      const label = `${sym.kind} ${sym.name} (${rel}:${sym.line}): ${detail}`;
      if (TYPE_KINDS.has(sym.kind) || isKitSymbol(rel, sym.name)) notes.push(`unconsumed ${label}`);
      else failures.push(`orphan symbol ${label}`);
      continue;
    }
    if (!real.some((c) => dirname(c.from) !== ownDir) && !isKitSymbol(rel, sym.name)) {
      sameDirOnly.push(`${sym.name} (${rel}:${sym.line}) <- ${real.map((c) => c.from).join(', ')}`);
    }
  }
}
if (sameDirOnly.length > 0) {
  notes.push(`${sameDirOnly.length} build-authored symbol(s) consumed only inside their own directory: ${sameDirOnly.join('; ')}`);
}

/* --------------------- E2b: public methods whose only caller is a selftest -- */

/**
 * The `pinCasket` shape. A public method the game never calls is dead code
 * wearing a passing test — and this is the one variant of deadness where the
 * selftest is not merely useless but actively misleading, because the method
 * has provable coverage and zero product callers.
 *
 * Only the masked case fails: a method called by a selftest and by nothing
 * else. A method called solely by its own class is internal-by-habit rather
 * than dead, so it is a note; failing that would be noise, and a noisy gate
 * gets switched off.
 */
const LIFECYCLE = new Set([
  'constructor', 'init', 'preload', 'create', 'update', 'preUpdate', 'postUpdate',
  'render', 'shutdown', 'destroy', 'resize', 'toJSON', 'get', 'set',
]);
const methodRe = /\n {2}(?:public\s+)?(?:override\s+)?(?:async\s+)?([a-z]\w*)\s*(?:<[^>]*>)?\s*\(/g;

for (const [rel, mod] of modules) {
  if (isSelftest(rel) || !mod.exports.some((s) => s.kind === 'class')) continue;
  const { code } = sourceOf(rel);
  const seen = new Set();
  for (let m = methodRe.exec(code); m !== null; m = methodRe.exec(code)) {
    const name = m[1];
    if (LIFECYCLE.has(name) || seen.has(name)) continue;
    seen.add(name);
    // A caller only counts if it imports the declaring module. Method names
    // collide across unrelated classes (`place()` exists on three of them), and
    // matching bare `.name(` text made this gate accuse the wrong file.
    const callers = files.filter((other) => (
      other !== rel && (edges.get(other)?.has(rel) ?? false) && sourceOf(other).code.includes(`.${name}(`)
    ));
    const product = callers.filter((other) => !isSelftest(other));
    if (callers.length === 0) continue; // never called anywhere: internal helper or E2 already fired
    if (product.length > 0) continue;
    if (isKitSymbol(rel, name) || isKitModule(rel)) {
      notes.push(`kit method ${name}() (${rel}) is called only by ${callers.join(', ')}`);
      continue;
    }
    failures.push(
      `orphan method ${name}() (${rel}): the only caller is ${callers.join(', ')} — `
      + 'a selftest is not a consumer, so this method has coverage and no product call site',
    );
  }
}

/* --------------------------------------------- E3: tuning leaves with readers */

const { loaded, skipped, failed } = await loadDataModules();
for (const entry of failed) failures.push(`could not load data module ${entry.rel}: ${entry.message}`);
if (skipped.length > 0) notes.push(`data modules skipped (import Phaser at runtime): ${skipped.join(', ')}`);

const roots = tuningRoots(loaded);
if (roots.length === 0) failures.push('no TUNING root found: src/config.ts must export TUNING');

let leafCount = 0;
const deadKitTuning = [];
for (const root of roots) {
  const leaves = tuningLeaves(root.value);
  leafCount += leaves.length;
  // The declaring file counts as a reader: `config.ts` derives
  // `PLAYER_BASE_STATS` from `TUNING.player.*`, which is a real read. Only
  // dotted accesses match, so the literal definitions never self-satisfy.
  const { reads, opaque } = scanTuningReads(root.name, files);
  if (opaque.length > 0) {
    notes.push(`${root.name} referenced without a key at ${opaque.slice(0, 6).join(', ')}${opaque.length > 6 ? ` (+${opaque.length - 6} more)` : ''} — those sites prove nothing about which leaves are read`);
  }
  for (const leaf of leaves) {
    if (leafIsRead(leaf, reads)) continue;
    // Provenance again: a kit number the chosen family never wired is the
    // template's debt, not this build's, and holding a game agent to it would
    // make the gate un-passable on day one. It is still named, in full, so the
    // debt is visible and fixable upstream instead of being laundered.
    if (isKitTuning(root.name, leaf)) deadKitTuning.push(`${root.name}.${leaf}`);
    else failures.push(`unread tuning ${root.name}.${leaf}: no reader in src/ — a number nothing can claim`);
  }
}
if (deadKitTuning.length > 0) {
  notes.push(`${deadKitTuning.length} kit tuning leaf/leaves unread by this family (template debt): ${deadKitTuning.join(', ')}`);
}

/* ------------------------------ E4: content references into a live registry -- */

/**
 * "An effect id registered nowhere." Anchored on evidence, not on a naming
 * convention: a registry only counts if `src/` indexes it dynamically
 * (`EFFECT_HOOKS[effectId]`), which proves ids are looked up in it at runtime.
 * A content field is then matched to the registry that covers most of its
 * distinct values; a value the winning registry does not hold, and which
 * appears as a literal nowhere else in `src/`, is content the game cannot
 * reach. Free-text fields resolve into no registry at all and never trigger.
 */
const registries = new Map();
for (const [, mod] of loaded) {
  for (const [name, value] of Object.entries(mod)) {
    if (value === null || typeof value !== 'object' || Array.isArray(value)) continue;
    const keys = Object.keys(value);
    if (keys.length > 0) registries.set(name, new Set(keys));
  }
}
// Registries declared but not exported are found in source text.
for (const rel of files) {
  const { code } = sourceOf(rel);
  // The annotation may itself contain `=` (`Record<string, (…) => void>`), so
  // the type is matched lazily up to the real assignment rather than as
  // "anything but `=`" — `EFFECT_HOOKS`, the registry this rule was written
  // for, is declared with exactly that signature and was being skipped.
  const declRe = /(?:const|let)\s+([A-Z][A-Z0-9_]{2,})\s*(?::[^;{}]*?)?=\s*\{/g;
  for (let m = declRe.exec(code); m !== null; m = declRe.exec(code)) {
    if (registries.has(m[1])) continue;
    const keys = objectLiteralKeys(code, code.indexOf('{', m.index + m[0].length - 1));
    if (keys.length > 0) registries.set(m[1], new Set(keys));
  }
}
/** Registries `src/` indexes with a computed key — the proof that ids are resolved through them. */
const indexedRegistries = new Map();
for (const rel of files) {
  const { code } = sourceOf(rel);
  for (const [name, keys] of registries) {
    if (new RegExp(`\\b${name}\\s*\\[`).test(code)) indexedRegistries.set(name, keys);
  }
}

function objectLiteralKeys(code, open) {
  if (open < 0) return [];
  const keys = [];
  let depth = 0;
  let i = open;
  for (; i < code.length; i += 1) {
    const c = code[i];
    if (c === '{' || c === '[' || c === '(') depth += 1;
    else if (c === '}' || c === ']' || c === ')') {
      depth -= 1;
      if (depth === 0) break;
    } else if (depth === 1) {
      const rest = code.slice(i, i + 80);
      const m = /^(?:'([^']+)'|"([^"]+)"|([A-Za-z_$][\w$]*))\s*:/.exec(rest);
      if (m !== null) {
        keys.push(m[1] ?? m[2] ?? m[3]);
        i += m[0].length - 1;
      }
    }
  }
  return keys;
}

/** Every string literal in `src/`, mapped to the files that spell it. */
const literalIndex = new Map();
for (const rel of files) {
  const { code } = sourceOf(rel);
  const re = /'([A-Za-z_][\w.:-]{1,48})'/g;
  for (let m = re.exec(code); m !== null; m = re.exec(code)) {
    const set = literalIndex.get(m[1]);
    if (set === undefined) literalIndex.set(m[1], new Set([rel]));
    else set.add(rel);
  }
}

const FREE_TEXT = /^(name|label|title|desc|description|blurb|copy|text|tip|hint|body|prompt|answer|question)$/i;
const fieldValues = new Map();
function collectRows(rel, node, depth = 0, rowId = null) {
  if (depth > 4 || node === null || typeof node !== 'object') return;
  if (Array.isArray(node)) {
    for (const item of node) collectRows(rel, item, depth + 1, rowId);
    return;
  }
  const id = typeof node.id === 'string' ? node.id : rowId;
  for (const [key, value] of Object.entries(node)) {
    if (typeof value === 'string') {
      if (key === 'id' || FREE_TEXT.test(key)) continue;
      const list = fieldValues.get(key);
      const record = { rel, rowId: id, value };
      if (list === undefined) fieldValues.set(key, [record]);
      else list.push(record);
    } else if (value !== null && typeof value === 'object') {
      collectRows(rel, value, depth + 1, id);
    }
  }
}
for (const [rel, mod] of loaded) {
  for (const value of Object.values(mod)) if (Array.isArray(value)) collectRows(rel, value);
}

let refFields = 0;
for (const [field, records] of fieldValues) {
  const distinct = new Map();
  for (const record of records) if (!distinct.has(record.value)) distinct.set(record.value, record);
  let best = null;
  for (const [name, keys] of indexedRegistries) {
    const hits = [...distinct.keys()].filter((v) => keys.has(v)).length;
    if (hits === 0) continue;
    if (best === null || hits > best.hits) best = { name, keys, hits };
  }
  // Demand the winner explain at least half the field before believing it is the
  // target. Half, not more: a field with two values — the shape a first dead
  // effect id actually arrives in — can never exceed 0.5, and that is exactly
  // the case worth catching.
  if (best === null || best.hits / distinct.size < 0.5) continue;
  refFields += 1;
  for (const record of distinct.values()) {
    if (best.keys.has(record.value)) continue;
    const elsewhere = [...(literalIndex.get(record.value) ?? [])].filter((u) => u !== record.rel);
    if (elsewhere.length > 0) continue;
    failures.push(
      `dead content ${record.rel}: ${record.rowId ?? '<row>'}.${field} = "${record.value}" is not a key of `
      + `${best.name} (which ${best.hits}/${distinct.size} sibling values do index) and appears in no other src/ file`,
    );
  }
}

/* ---------------------------------------------------------------- output --- */

const symbolCount = [...modules.values()].reduce((n, m) => n + m.exports.length, 0);
const summary = `checked ${files.length} modules, ${symbolCount} exported symbols, `
  + `${leafCount} tuning leaves, ${refFields} content reference field(s)`;

if (process.argv.includes('--json')) {
  console.log(JSON.stringify({ summary, failures, notes }, null, 2));
  if (failures.length > 0) process.exitCode = 1;
} else {
  report('consumer-edge check', { failures, notes, summary });
}
